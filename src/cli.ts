#!/usr/bin/env node
import { Command, CommanderError, Option } from 'commander';
import { readFileSync } from 'node:fs';
import { cli } from './command.js';
import { configPath, integer, name, resolveConfig, saveSettings, settings, type Options } from './config.js';
import { createInput, parseRef, queryInput, readJson, readJsonl, updateInput } from './input.js';
import { importDocuments, planBatches } from './import-workflow.js';
import { definitelyRejected, describeError, InputError, ManagementError, isInputError, parseError } from './errors.js';
import { Output, type Envelope } from './output.js';
import { checkConnection, runtime } from './runtime.js';
import { CredentialVault, credentialReference } from './credentials.js';
import { initialize, interactiveInit } from './init.js';
import { formatInit } from './init-output.js';
import { serveMcp } from './mcp.js';
import { agentNames } from './agents.js';
import { login, logout, management } from './account.js';
import { usage, formatUsage } from './usage.js';
import { organizations, projects, createProject, useProject } from './projects.js';

const output = new Output();
output.protect(process.env.LAMBDADB_API_KEY);
if (process.env.LAMBDADB_API_KEY_ENV) output.protect(process.env[process.env.LAMBDADB_API_KEY_ENV]);
let commandName = 'lambdadb';
let target: Record<string, unknown> | undefined;
let mutationStarted = false;

const program = new Command()
  .name('lambdadb')
  .description('Set up LambdaDB, manage projects, view usage and work with data and coding agents. Only init prompts; all other commands are non-interactive.')
  .version(JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version)
  .option('--json', 'Emit one versioned JSON result on stdout; diagnostics stay on stderr')
  .addOption(new Option('--api-url <url>', 'Account management API origin (login reuses the saved origin, otherwise https://api.lambdadb.ai)').helpGroup('Advanced connection options:'))
  .option('--endpoint <url>', 'Project data API origin (overrides LAMBDADB_ENDPOINT and saved configuration)')
  .option('--project <name>', 'Existing project (overrides LAMBDADB_PROJECT and saved configuration)')
  .option('--api-key-env <name>', 'Environment variable holding the key; never pass a key as an argument')
  .addOption(new Option('--credential-store <store>', 'OS credential backend: auto, keychain, windows, secret-service or keyutils (account setup selects auto)').helpGroup('Advanced connection options:'))
  .addOption(new Option('--credential-id <uuid>', 'Non-secret saved credential reference (normally generated by init)').helpGroup('Advanced connection options:'))
  .option('--config <path>', 'Configuration path (overrides LAMBDADB_CONFIG)')
  .option('--timeout-ms <ms>', 'Data API: total command budget; account/project API: per HTTP request, 1–3600000 ms (default 30000)')
  .exitOverride()
  // Parse errors are reported through the CLI envelope; help for a missing subcommand still prints.
  .configureOutput({ outputError: () => {} })
  .addHelpText('after', '\nExamples:\n  lambdadb init\n  lambdadb doctor --json\n  lambdadb query --collection demo-docs --ref branch:main --file examples/query.json --json\n\nExit codes: 0 success, 2 input/config error, 3 API/request failure, 4 partial import, 5 unknown write outcome.');

function result(data: unknown, summary: string, exitCode = 0) {
  const envelope: Envelope = { schemaVersion: 1, command: commandName, ok: exitCode === 0, target, data };
  output.emit(envelope, summary);
  process.exitCode = exitCode;
}

type Context = ReturnType<typeof runtime>;
async function connected(command: Command, action: (ctx: Context) => Promise<void>) {
  const config = await resolveConfig(command.optsWithGlobals());
  output.protect(config.apiKey);
  target = { endpoint: config.endpoint, project: config.project };
  const ctx = runtime(config);
  try { await action(ctx); } finally { ctx.close(); }
}

function scoped(command: Command): string {
  const collection = name(command.opts().collection, 'Collection name');
  target = { ...target, collection };
  return collection;
}

program.hook('preSubcommand', (_parent, command) => {
  // Name the command in parse-error envelopes and reserve MCP stdout before preAction runs.
  commandName = command.name();
});

program.hook('preAction', (_parent, command) => {
  output.json = !!command.optsWithGlobals().json;
  commandName = command.name();
  if (command.parent && command.parent !== program) commandName = `${command.parent.name()} ${commandName}`;
});

program.command('configure')
  .description('Save endpoint, project and API-key environment variable name (no secret is saved)')
  .action(async (_opts, cmd: Command) => {
    const saved = await saveSettings(cmd.optsWithGlobals() as Options);
    result(saved, 'Configuration saved. Supply the key in the selected environment variable, then run doctor.');
  });

program.command('init')
  .description('Connect through Console or existing credentials, then install agent MCP configuration and a usage skill')
  .option('--no-browser', 'Skip automatic browser opening; sign in and approve at the printed URL on this or another device')
  .option('--non-interactive', 'Require explicit agent/scope choices; never prompt')
  .option('--agents <names>', `Comma-separated ${agentNames} subset, or none`)
  .option('--scope <scope>', 'Where to install agent settings and skills: project (current directory) or user; does not change CLI config location')
  .option('--write-tools', 'Explicitly enable MCP write tools (default: read-only)')
  .addHelpText('after', '\nGet started: lambdadb init\nSSH: lambdadb init --no-browser (browser approval is still required on another device).\nReruns offer to reuse the current connection or select another project.\nAccount setup reuses a valid login, or guides signup/login and CLI approval in a browser. Select or create a project in the terminal; secrets are saved only in the OS credential store.\nManual/CI setup: obtain a project key in Console and export it securely; init saves only the environment-variable name.\nAutomation example (export LAMBDADB_API_KEY first):\n  lambdadb init --non-interactive --agents codex,claude,cursor --scope project --endpoint https://api.lambdadb.ai --project my-project --json')
  .action(async (_opts, cmd: Command) => {
    const options = cmd.optsWithGlobals();
    const interactive = interactiveInit(options);
    const data = await initialize(options, output);
    target = { endpoint: data.settings.endpoint, project: data.settings.project };
    output.emit({ schemaVersion: 1, command: commandName, ok: true, target, data }, formatInit(data, configPath(options), interactive), false);
  });

program.command('login').description('Authorize account management in a browser and save a separate OS session')
  .option('--no-browser', 'Skip automatic browser opening; sign in and approve at the printed URL on this or another device')
  .action(async (_opts, cmd: Command) => {
    const account = await login(cmd.optsWithGlobals(), output);
    output.diagnostic(`Next: run ${cli} init for guided project and agent setup, or ${cli} orgs list to manage projects with explicit commands. Keep the same --config path if you supplied one.`);
    result(account, 'Account login saved. Project connections and agent settings are unchanged.');
  });
program.command('logout').description('Revoke the saved account session and remove it locally; keep project connections')
  .action(async (_opts, cmd: Command) => { await logout(cmd.optsWithGlobals(), output); result({ loggedOut: true, projectKeysRevoked: false }, 'Account logged out. Project keys and agent connections are unchanged.'); });
program.command('orgs').description('Manage account Organizations').command('list')
  .action(async (_opts, cmd: Command) => result({ organizations: await organizations(cmd.optsWithGlobals(), output) }, 'Accessible Organizations.'));
const projectCommands = program.command('projects').description('List, create and select projects using the saved account session');
projectCommands.command('list').requiredOption('--org-id <uuid>', 'Organization ID')
  .action(async (opts, cmd: Command) => result({ projects: await projects(cmd.optsWithGlobals(), opts.orgId, output) }, 'Projects in the selected Organization.'));
projectCommands.command('regions').description('List available regions before project creation')
  .action(async (_opts, cmd: Command) => { const api = await management(cmd.optsWithGlobals(), output); result(await api.request('regions'), 'Project regions.'); });
projectCommands.command('create').option('--org-id <uuid>', 'Existing Organization ID').option('--default-org', 'Explicitly prepare the default Organization on submission')
  .requiredOption('--name <name>', 'Project name').requiredOption('--region <region>', 'Region from projects regions')
  .action(async (opts, cmd: Command) => {
    const created = await createProject(cmd.optsWithGlobals(), opts, output);
    result(created, 'Project requested. Check projects list for ACTIVE status; creation does not establish search readiness.');
  });
projectCommands.command('use').requiredOption('--org-id <uuid>', 'Organization ID').requiredOption('--project-id <uuid>', 'Project ID')
  .option('--issue-key', 'Explicitly issue a new project key, including replacement of a saved connection')
  .action(async (opts, cmd: Command) => result(await useProject(cmd.optsWithGlobals(), opts.orgId, opts.projectId, !!opts.issueKey, output), 'CLI project selected. Agent configurations are unchanged.'));

program.command('usage')
  .description('Show current project usage: Free quotas or Pay-As-You-Go recorded usage and list-rate cost estimates')
  .option('--org-id <uuid>', 'Show the entire Organization instead of the saved project; requires account login')
  .option('--project-id <uuid>', 'Filter --org-id to one project')
  .option('--month <YYYY-MM>', 'UTC calendar month (default current); historical Free quotas are unavailable')
  .addHelpText('after', '\nExamples:\n  lambdadb usage\n  lambdadb usage --org-id ORG_UUID --json\n  lambdadb usage --org-id ORG_UUID --project-id PROJECT_UUID --month 2026-09\nFree shows its current quota window, without price conversion. Cost estimates require owner/admin and exclude credits and billing adjustments. No login, key issuance or service writes start automatically.')
  .action(async (_opts, cmd: Command) => {
    const data = await usage(cmd.optsWithGlobals(), output);
    output.emit({ schemaVersion: 1, command: 'usage', ok: true, target: { organization: data.organization.id }, data }, formatUsage(data), false);
  });

program.command('mcp')
  .description('Launch the existing stdio MCP package with runtime credential forwarding (used by init)')
  .option('--write-tools', 'Explicitly enable MCP write tools (default: read-only)')
  .action(async (_opts, cmd: Command) => {
    const opts = cmd.optsWithGlobals();
    if (opts.json) throw new InputError('The mcp command uses stdout exclusively for MCP; remove --json.');
    const config = await resolveConfig(opts, true);
    output.protect(config.apiKey);
    if ([`\${${config.apiKeyEnv}}`, `\${env:${config.apiKeyEnv}}`, `{env:${config.apiKeyEnv}}`].includes(config.apiKey)) {
      throw new InputError(`The agent did not expand ${config.apiKeyEnv}. Export it securely in the agent launch environment and restart the agent.`);
    }
    process.exitCode = await serveMcp(config, !!opts.writeTools);
  });

program.command('credentials').description('Manage local OS credential references').command('remove')
  .description('Delete this connection’s local OS credential; keep metadata and do not revoke the server key')
  .action(async (_opts, cmd: Command) => {
    const selected = await settings(cmd.optsWithGlobals());
    if (!selected.credentialStore || !selected.credentialId) throw new InputError('This connection uses an environment variable. Unset it in your shell or secret manager; revoke the project key separately in Console.');
    await new CredentialVault().remove({ ...selected, ...credentialReference(selected.credentialStore, selected.credentialId) });
    result({ credentialStore: selected.credentialStore, credentialKeyId: selected.credentialKeyId, credentialKeyName: selected.credentialKeyName, serverKeyRevoked: false },
      'Local credential removed. Connection references remain. Revoke the project key in Console if you no longer need it.');
  });

program.command('doctor')
  .description('Check configuration, authentication and project collection-list access')
  .action(async (_opts, cmd: Command) => connected(cmd, async ({ client, options }) => {
    result(await checkConnection({ client, options }), 'Connection verified using the project collection-list API.');
  }));

const collections = program.command('collections').description('List, describe, create and update collections');
collections.command('list')
  .description('Fetch one page by default, or use the SDK iterator for all pages')
  .option('--size <count>', 'Page size, 1–100', '20')
  .option('--page-token <token>', 'Opaque continuation token')
  .option('--all', 'Fetch all pages within the total timeout (results are buffered)')
  .action(async (opts, cmd: Command) => {
    const size = integer(opts.size, 'Page size', 1, 100);
    await connected(cmd, async ({ client, options }) => {
      const params = { size, pageToken: opts.pageToken };
      if (!opts.all) {
        const page = await client.listCollections(params, options);
        result(page, `${page.collections.length} collection(s)${page.nextPageToken ? '; more pages available' : ''}.`);
      } else {
        const items = [];
        for await (const page of client.listCollectionsPages(params, options)) items.push(...page.collections);
        result({ collections: items }, `${items.length} collection(s).`);
      }
    });
  });

collections.command('describe')
  .description('Get collection metadata; counts describe the committed main branch')
  .requiredOption('--collection <name>', 'Collection name')
  .action(async (_opts, cmd: Command) => connected(cmd, async ({ client, options }) => {
    const collection = scoped(cmd);
    result(await client.collection(collection).get(options), 'Collection metadata (main-branch counts are not a readiness signal).');
  }));

collections.command('create')
  .description('Create a collection from a JSON field-to-index map')
  .requiredOption('--collection <name>', 'New collection name')
  .requiredOption('--index-config <path>', 'JSON field-to-index map; native embedding or legacy managedEmbedding:true supported')
  .addHelpText('after', '\nExamples:\n  lambdadb collections create --collection demo-docs --index-config examples/index-config.json\n  lambdadb collections create --collection native-docs --index-config examples/index-config-native.json')
  .action(async (opts, cmd: Command) => {
    const input = createInput(name(opts.collection, 'Collection name'), await readJson(opts.indexConfig));
    await connected(cmd, async ({ client, options }) => {
      scoped(cmd);
      mutationStarted = true;
      const created = await client.createCollection(input, { ...options, retries: { strategy: 'none' } });
      result({ ...created, state: 'created', searchable: 'not_verified' }, 'Collection created; query-serving readiness has not been verified.');
    });
  });

collections.command('update')
  .description('Update collection index configuration from a JSON field-to-index map')
  .requiredOption('--collection <name>', 'Existing collection name')
  .requiredOption('--index-config <path>', 'JSON field-to-index map; native dimensions/similarity go inside embedding')
  .addHelpText('after', '\nExample:\n  lambdadb collections update --collection native-docs --index-config examples/index-config-native.json --json\n\nThe server validates permitted index changes. Older servers require managedEmbedding:true.')
  .action(async (opts, cmd: Command) => {
    name(opts.collection, 'Collection name');
    const input = updateInput(await readJson(opts.indexConfig));
    await connected(cmd, async ({ client, options }) => {
      const collection = scoped(cmd);
      mutationStarted = true;
      const updated = await client.collection(collection).update(input, { ...options, retries: { strategy: 'none' } });
      result({ ...updated, state: 'updated', searchable: 'not_verified' }, 'Collection updated; query-serving readiness has not been verified.');
    });
  });

const docs = program.command('docs').description('Import JSONL and fetch documents by ID');
docs.command('import')
  .description('Validate JSONL, submit sequential batches, stop on first error; acceptance is not search readiness')
  .requiredOption('--collection <name>', 'Collection name')
  .requiredOption('--branch <name>', 'Explicit writable branch (for example main)')
  .requiredOption('--file <path>', 'UTF-8 JSONL file, at most 64 MiB and 100000 documents')
  .addOption(new Option('--mode <mode>', 'SDK write method').choices(['upsert', 'bulk']).default('upsert'))
  .option('--batch-size <count>', 'Maximum documents per batch, 1–10000', '1000')
  .option('--batch-bytes <bytes>', 'Serialized byte cap (default 4000000 upsert, 16000000 bulk)')
  .action(async (opts, cmd: Command) => {
    name(opts.collection, 'Collection name');
    const branch = name(opts.branch, 'Branch name');
    const bulk = opts.mode === 'bulk';
    const batchSize = integer(opts.batchSize, 'Batch size', 1, 10000);
    const maxBytes = integer(opts.batchBytes ?? (bulk ? '16000000' : '4000000'), 'Batch bytes', 64, bulk ? 64000000 : 4000000);
    const rows = await readJsonl(opts.file);
    const batches = planBatches(rows, branch, batchSize, maxBytes, bulk);
    await connected(cmd, async ({ client, options }) => {
      const collection = scoped(cmd);
      target = { ...target, branch };
      output.diagnostic(`Validated ${rows.length} document(s); submitting ${batches.length} batch(es) using ${opts.mode}.`);
      const imported = await importDocuments(client.collection(collection).docs, batches, branch, bulk, options, batch => {
        output.diagnostic(`Batch ${batch.batch}: ${batch.state}, ${batch.documents} document(s), lines ${batch.firstLine}–${batch.lastLine}.`);
      });
      const exitCode = imported.state === 'accepted' ? 0 : imported.state === 'unknown' ? 5 : imported.state === 'partial' ? 4 : 3;
      result(imported, `${imported.accepted}/${imported.total} document(s) accepted; search visibility not verified.`, exitCode);
      if (exitCode) output.diagnostic('Import stopped. Inspect batch outcomes and the selected branch before retrying; automatic resume is not supported.');
    });
  });

docs.command('fetch')
  .description('Fetch up to 100 IDs at an explicit ref; missing IDs are a successful empty/partial result')
  .requiredOption('--collection <name>', 'Collection name')
  .requiredOption('--ref <kind:name>', 'branch:NAME, tag:NAME or alias:NAME')
  .requiredOption('--ids <id...>', 'One or more IDs (separate with spaces)')
  .option('--consistent-read', 'Overlay eligible pending writes; direct branch only, excludes bulk imports')
  .option('--include-vectors', 'Include vector fields in returned documents')
  .action(async (opts, cmd: Command) => {
    const ref = parseRef(opts.ref);
    if (opts.ids.length > 100 || opts.ids.some((id: string) => !id)) throw new InputError('Fetch requires 1–100 nonempty IDs.');
    if (opts.consistentRead && ref.kind !== 'branch') throw new InputError('Consistent reads require a direct branch ref.');
    await connected(cmd, async ({ client, options }) => {
      const collection = scoped(cmd);
      target = { ...target, ref };
      const fetched = await client.collection(collection).docs.fetch({
        ids: opts.ids, includeVectors: opts.includeVectors ?? false,
        ...(ref.kind === 'branch' ? { ref, consistentRead: !!opts.consistentRead } : { ref, consistentRead: false }),
      }, options);
      const found = new Set(fetched.docs.map(item => item.doc.id));
      const { docsUrl: _signedUrl, ...data } = fetched;
      result({ ...data, missingIds: opts.ids.filter((id: string) => !found.has(id)) }, `${fetched.docs.length} document(s) fetched.`);
    });
  });

program.command('query')
  .description('Submit a supported query request JSON file; empty matches are a successful result')
  .requiredOption('--collection <name>', 'Collection name')
  .requiredOption('--ref <kind:name>', 'branch:NAME, tag:NAME or alias:NAME; must match any ref in the file')
  .requiredOption('--file <path>', 'JSON request body; omit query for match-all, use size:0 with facets for counts only; optional rerank is per query')
  .addHelpText('after', '\nBayesian: exactly two unboosted subqueries, including Boolean descendants; no nested fusion.\nWithout rerank, set candidateSize with 1 <= size <= candidateSize <= 100.\nWith rerank, omit top-level candidateSize and use rerank.candidateSize (server default preserved).\n  lambdadb query --collection native-docs --ref branch:main --file examples/query-bayesian.json --json\n  lambdadb query --collection native-docs --ref branch:main --file examples/query-bayesian-rerank.json --json')
  .addHelpText('after', '\nExamples:\n  lambdadb query --collection demo-docs --ref branch:main --file examples/query.json --json\n  lambdadb query --collection demo-docs --ref branch:main --file examples/query-facets-only.json --json\n  lambdadb query --collection demo-docs --ref branch:main --file examples/query-with-facets.json --json\n  lambdadb query --collection demo-docs --ref branch:main --file examples/query-rerank.json --json')
  .action(async (opts, cmd: Command) => {
    const ref = parseRef(opts.ref);
    const input = queryInput(await readJson(opts.file), ref);
    await connected(cmd, async ({ client, options }) => {
      const collection = scoped(cmd);
      target = { ...target, ref };
      const queried = await client.collection(collection).query(input, options);
      const { docsUrl: _signedUrl, ...data } = queried;
      result(data, `${queried.docs.length} match(es).`);
    });
  });

try {
  if (process.argv.length <= 2) program.help();
  await program.parseAsync(process.argv);
} catch (error) {
  if (error instanceof CommanderError && error.exitCode === 0) {
    process.exitCode = 0;
  } else {
    output.json ||= process.argv.includes('--json');
    const failure = error instanceof CommanderError ? parseError(error, commandName) : error;
    const unknownWrite = (mutationStarted && !definitelyRejected(failure)) || (failure instanceof ManagementError && ['write_outcome_unknown', 'issuance_unconfirmed'].includes(failure.code));
    const exitCode = isInputError(failure) ? 2 : unknownWrite ? 5 : 3;
    if (commandName === 'mcp') {
      const safe = describeError(failure);
      output.diagnostic([safe.message, safe.hint].filter(Boolean).join(' '));
    } else output.emit({
      schemaVersion: 1, command: commandName, ok: false, target,
      ...(unknownWrite ? { data: { state: 'unknown', searchable: 'not_verified' } } : {}),
      error: describeError(failure),
    }, unknownWrite ? 'Write outcome unknown. Inspect the target before retrying.' : 'Command failed.');
    process.exitCode = exitCode;
  }
}
