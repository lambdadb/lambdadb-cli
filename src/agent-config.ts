import { applyEdits, modify, parse as parseJson, type ParseError } from 'jsonc-parser';
import { parse as parseToml } from 'smol-toml';
import type { SelectedSettings } from './config.js';
import { credentialReference } from './credentials.js';
import { InputError } from './errors.js';

export type McpLaunch = { command: string; args: string[]; apiKeyEnv?: string; runtimeEnv?: string[] };
type Server = { command: string | string[]; args?: string[]; env_vars?: string[];
  env?: Record<string, string>; environment?: Record<string, string>; type?: string };
type ServerFactory = (launch: McpLaunch) => Server;
type JsonMapPath = readonly string[] | ((value: Record<string, unknown>) => readonly string[]);
const begin = '# BEGIN lambdadb init';
const end = '# END lambdadb init';

export function mcpLaunch(selected: SelectedSettings, writeTools: boolean, cliVersion: string): McpLaunch {
  const stored = selected.credentialStore ? credentialReference(selected.credentialStore, selected.credentialId) : undefined;
  return { command: 'npx', apiKeyEnv: selected.credentialStore ? undefined : selected.apiKeyEnv,
    runtimeEnv: selected.credentialStore === 'secret-service' ? ['DBUS_SESSION_BUS_ADDRESS', 'XDG_RUNTIME_DIR'] : [],
    args: ['-y', `@functional-systems/lambdadb-cli@${cliVersion}`, 'mcp',
      '--endpoint', selected.endpoint, '--project', selected.project,
      ...(stored ? ['--credential-store', stored.credentialStore, '--credential-id', stored.credentialId] : ['--api-key-env', selected.apiKeyEnv]),
      ...(writeTools ? ['--write-tools'] : [])] };
}

function object(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value);
}

// Only entries generated by init may be updated. User additions to our entry
// cause a conflict instead of silently dropping their settings.
function managedServer(value: unknown, createServer: ServerFactory): boolean {
  if (!object(value)) return false;
  const command = Array.isArray(value.command) ? value.command[0] : value.command;
  const a = Array.isArray(value.command) ? value.command.slice(1) : value.args;
  if (command !== 'npx' || !Array.isArray(a)) return false;
  if (a.some(v => typeof v !== 'string') || !/^@functional-systems\/lambdadb-cli@[\w.+-]+$/.test(a[1] ?? '')
    || a[0] !== '-y' || a[2] !== 'mcp' || a[3] !== '--endpoint' || a[5] !== '--project') return false;
  const stored = a[7] === '--credential-store' && ['keychain', 'windows', 'secret-service', 'keyutils'].includes(a[8]) && a[9] === '--credential-id';
  const length = stored ? 11 : 9;
  if ((!stored && a[7] !== '--api-key-env') || ![length, length + 1].includes(a.length) || (a.length > length && a[length] !== '--write-tools')) return false;
  const expected = createServer({ command: 'npx', args: a, apiKeyEnv: stored ? undefined : a[8], runtimeEnv: stored && a[8] === 'secret-service' ? ['DBUS_SESSION_BUS_ADDRESS', 'XDG_RUNTIME_DIR'] : [] });
  return Object.keys(value).length === Object.keys(expected).length
    && Object.entries(expected).every(([key, item]) => JSON.stringify(value[key]) === JSON.stringify(item));
}

function conflict(path: string): never {
  throw new InputError(`Existing LambdaDB configuration in ${path} was not generated by init or has been edited. Preserve or rename that entry before rerunning init; no overwrite was performed.`);
}

export function jsonConfig(path: string, text: string | undefined, launch: McpLaunch, createServer: ServerFactory,
  mapPath: JsonMapPath = ['mcpServers']): string {
  const errors: ParseError[] = [];
  const value: unknown = parseJson(text ?? '{}', errors, { allowTrailingComma: true });
  if (errors.length || !object(value)) {
    throw new InputError(`Invalid agent JSON configuration: ${path}. Fix it before rerunning init.`);
  }
  const keys = typeof mapPath === 'function' ? mapPath(value) : mapPath;
  let container: Record<string, unknown> = value;
  for (const key of keys) {
    const child = container[key];
    if (child !== undefined && !object(child)) {
      throw new InputError(`Invalid agent JSON configuration: ${path}. ${keys.join('.')} must contain objects.`);
    }
    container = (child ?? {}) as Record<string, unknown>;
  }
  const previous = container.lambdadb;
  if (previous !== undefined && !managedServer(previous, createServer)) conflict(path);
  const desired = createServer(launch);
  if (JSON.stringify(previous) === JSON.stringify(desired)) return text!;
  const source = text ?? '{}\n';
  return applyEdits(source, modify(source, [...keys, 'lambdadb'], desired, {
    formattingOptions: { insertSpaces: true, tabSize: 2 },
  }));
}

export function strictJsonConfig(path: string, text: string | undefined, launch: McpLaunch, createServer: ServerFactory,
  mapPath: JsonMapPath = ['mcpServers']): string {
  try { JSON.parse(text ?? '{}'); }
  catch { throw new InputError(`Init requires strict JSON for ${path}. Remove comments or trailing commas before rerunning init.`); }
  return jsonConfig(path, text, launch, createServer, mapPath);
}

function tomlBlock(value: { args?: unknown; env_vars?: unknown }): string {
  return `${begin}\n[mcp_servers.lambdadb]\ncommand = "npx"\nargs = ${JSON.stringify(value.args)}\nenv_vars = ${JSON.stringify(value.env_vars)}\n${end}\n`;
}

export function tomlConfig(path: string, text: string | undefined, launch: McpLaunch, createServer: ServerFactory): string {
  const source = text ?? '';
  let parsed;
  try { parsed = parseToml(source); }
  catch { throw new InputError(`Invalid agent TOML configuration: ${path}. Fix it before rerunning init.`); }
  const servers = parsed.mcp_servers;
  if (servers !== undefined && !object(servers)) conflict(path);
  const previous = object(servers) ? servers.lambdadb : undefined;
  const block = tomlBlock(createServer(launch));
  const start = source.indexOf(begin);
  let after: string;
  if (start < 0) {
    if (previous !== undefined || source.includes(end)) conflict(path);
    after = source + (source.endsWith('\n') || !source ? '' : '\n') + '\n' + block;
  } else {
    const finish = source.indexOf(end, start);
    if (finish < 0 || source.indexOf(begin, start + begin.length) >= 0 || source.indexOf(end, finish + end.length) >= 0
      || !managedServer(previous, createServer)) conflict(path);
    const stop = finish + end.length + (source[finish + end.length] === '\n' ? 1 : 0);
    // Refuse to remove any unrelated sections/settings hidden inside markers.
    let managed;
    try { managed = parseToml(source.slice(start, stop)); } catch { conflict(path); }
    if (Object.keys(managed).length !== 1 || !object(managed.mcp_servers)
      || Object.keys(managed.mcp_servers).length !== 1 || !managedServer(managed.mcp_servers.lambdadb, createServer)) conflict(path);
    if (source.slice(start, stop) !== tomlBlock(previous as { args: unknown; env_vars: unknown })) conflict(path);
    after = source.slice(0, start) + block + source.slice(stop);
  }
  // Appending a table is unsafe when an existing inline table seals mcp_servers.
  try { parseToml(after); }
  catch { throw new InputError(`Cannot safely add LambdaDB to ${path}. Expand inline MCP tables before rerunning init.`); }
  return after;
}
